/**
 * Get gameplay stats for a monster sprite.
 *
 * @param spriteName - Monster sprite name (e.g., 'slm')
 * @returns The stats, or undefined when the monster has none
 */
export function getMonsterStats(spriteName: string): MonsterStats | undefined {
    return MONSTER_STATS.find(stats => stats.spriteName === spriteName);
}

/**
 * Converts a step duration in milliseconds to the Monster movement speed slider value (0-100),
 * the inverse of the slider mapping in `Monster` (0 = 1000ms per step, 100 = 200ms per step).
 */
export function movementSpeedMsToSlider(movementSpeedMs: number): number {
    return Math.min(100, Math.max(0, (1000 - movementSpeedMs) / 8));
}

