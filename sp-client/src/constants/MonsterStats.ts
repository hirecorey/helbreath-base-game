/**
 * A spell a monster can cast. While chasing the player, the monster rolls each entry's chance on every decision;
 * one of the spells that pass is cast instead of moving or meleeing.
 */
export interface MonsterSpellEntry {
    /** Spell id from `Spells.ts` */
    spellId: number;
    /** 0-1 chance this spell is cast instead of a normal attack */
    castProbability: number;
}

/**
 * Gameplay stats for a monster type. Visual data (sprites, sounds, animations) lives in `Monsters.ts`;
 * entries are joined on `spriteName`.
 */
export interface MonsterStats {
    /** Sprite name without extension; matches `MonsterData.spriteName` in `Monsters.ts` */
    spriteName: string;
    /** Display name */
    name: string;
    /** Max hit points */
    hp: number;
    /** Milliseconds per one-cell movement step (200 = fast, 1000 = slow) */
    movementSpeedMs: number;
    /** Full attack animation duration in milliseconds */
    attackSpeedMs: number;
    /** Inclusive lower bound of the damage roll */
    attackDamageMin: number;
    /** Inclusive upper bound of the damage roll */
    attackDamageMax: number;
    /** Attack reach in cells */
    attackRange: number;
    /** A target within this many cells can start a chase */
    chaseDistance: number;
    /** A chase is abandoned when the target gets farther than this many cells */
    chaseMaxDistance: number;
    /** Extra idle time after landing a hit, in milliseconds */
    attackRecoveryTimeMs: number;
    /** Lower bound of the random rest after reaching a wander destination, in milliseconds */
    minIdleTimeMs: number;
    /** Upper bound of the random rest after reaching a wander destination, in milliseconds */
    maxIdleTimeMs: number;
    /** How a hit affects the target */
    attackType: AttackType;
    /** When true, a hit (Interrupt) also stuns the player for `attackStunDurationMs` */
    stunsTarget: boolean;
    /** Stun duration in milliseconds when `stunsTarget` is true */
    attackStunDurationMs: number;
    /** Who this monster fights */
    allegiance: MonsterAllegiance;
    /** When true, attacks are ranged (arrow travel time before damage) */
    rangedAttack: boolean;
    /** Spells this monster can cast */
    spells: MonsterSpellEntry[];
    /** Delay before a dead spawn-area monster is replaced, in milliseconds */
    respawnTimeMs: number;
}

